FIGDIR = os.path.join(os.path.dirname(__file__), "..", "figures")
LOGDIR = os.path.join(os.path.dirname(__file__), "..", "logs")


def savefig(fig, name):
    os.makedirs(FIGDIR, exist_ok=True)
    path = os.path.abspath(os.path.join(FIGDIR, name))
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print(f"saved {path}")


def _plain(obj):
    """NumPy scalars and arrays as the JSON equivalents, recursively.

    ``json`` refuses ``np.float64`` and ``np.ndarray``. Converting at the
    boundary keeps the stored numbers at full precision: rounding here would put
    the rounding inside the evidence rather than inside the README.
    """
    if isinstance(obj, dict):
        return {str(k): _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return _plain(obj.tolist())
    if isinstance(obj, np.generic):
        return _plain(obj.item())
    if isinstance(obj, float) and (np.isnan(obj) or np.isinf(obj)):
        # json would write NaN/Infinity, which a strict parser rejects.
        return str(obj)
    return obj


def save_results(name, payload):
    """Write the numbers the README quotes about one experiment to ``logs/``.

    Every figure is regenerated by ``reproduce.sh`` and checked byte-for-byte
    against its committed copy, but the README's tables are transcribed by hand
    from the printed output, and nothing checked those. Writing the measurement
    next to the figure gives ``tests/test_readme_numbers.py`` something to hold
    the prose against, and gives the drift check in ``reproduce.sh`` a second
    kind of artifact to notice.

    Keys are sorted and floats kept at full precision, so a rerun that changes
    nothing writes byte-identical JSON.
    """
    os.makedirs(LOGDIR, exist_ok=True)
    path = os.path.abspath(os.path.join(LOGDIR, name + ".json"))
    with open(path, "w") as f:
        json.dump(_plain(payload), f, indent=2, sort_keys=True, allow_nan=False)
        f.write("\n")
    print(f"wrote {path}")


def print_table(rows, cols):
    """Minimal aligned table printer: rows = list of dicts, cols = keys."""
    def fmt(v):
        return f"{v:.3f}" if isinstance(v, float) else str(v)

    widths = {c: max(len(c), *(len(fmt(r[c])) for r in rows)) for c in cols}
    header = "  ".join(c.rjust(widths[c]) for c in cols)
    print(header)
    print("-" * len(header))
    for r in rows:
        print("  ".join(fmt(r[c]).rjust(widths[c]) for c in cols))
